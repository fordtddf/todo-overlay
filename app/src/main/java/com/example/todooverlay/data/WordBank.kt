    /**
     * 挑 [count] 个没出现过的词。
     *
     * @param seen 已经出过的词
     * @return 本次选中的词，以及更新后的 seen 集合（词库轮完会自动清空重来）
     */
    fun pick(seen: Set<String>, count: Int = PER_POPUP): Pair<List<Word>, Set<String>> {
        val remaining = all.filter { it.text !in seen }
        // 剩下的不够一轮了：重置，从全表重新挑
        if (remaining.size < count) {
            val fresh = all.shuffled().take(count)
            return fresh to fresh.map { it.text }.toSet()
        }
        val picked = remaining.shuffled().take(count)
        return picked to (seen + picked.map { it.text })
    }
